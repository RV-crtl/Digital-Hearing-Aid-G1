# Run the actual STM32CubeIDE ARM compiler, keep all evidence, and never flash.
[CmdletBinding()]
param([string]$CubeIDEExe="")
Set-StrictMode -Version Latest
$ErrorActionPreference = 'Stop'
$Root = Split-Path -Parent $MyInvocation.MyCommand.Path
$Destination = Join-Path $Root 'Validation\results'
New-Item -ItemType Directory -Force -Path $Destination | Out-Null
$Stamp = Get-Date -Format 'yyyyMMdd_HHmmss'
$Session = Join-Path $Destination "G1_R19_build_$Stamp"
New-Item -ItemType Directory -Force -Path $Session | Out-Null
$Transcript = Join-Path $Session 'build_console.log'
$ExitCode = 1
try {
    Start-Transcript -Path $Transcript -Force | Out-Null
    Write-Host 'G1 R19: Clean/Build through the installed STM32CubeIDE ARM toolchain.'
    # Prevent evidence from an earlier run being misclassified as this build.
    foreach ($old in @('g1_arm_build.log','g1_arm_build_stderr.log','g1_arm_build.json')) {
        $oldPath = Join-Path $Destination $old
        if (Test-Path -LiteralPath $oldPath) { Remove-Item -LiteralPath $oldPath -Force }
    }
    Write-Host 'Running mandatory CubeMX/STM32CubeIDE 1.19 source restoration...' -ForegroundColor Cyan
    & (Join-Path $Root 'PREPARE_PROJECT.ps1')
    if ($LASTEXITCODE -ne 0) { throw "PREPARE_PROJECT failed, code $LASTEXITCODE" }
    $py=Get-Command py -ErrorAction SilentlyContinue
    if($py) { & py -3 (Join-Path $Root 'Tools\r14_build_guard.py') }
    else { & python (Join-Path $Root 'Tools\r14_build_guard.py') }
    if ($LASTEXITCODE -ne 0) { throw "R19 source ownership test failed, code $LASTEXITCODE" }
    if ($CubeIDEExe) {
        & (Join-Path $Root 'G1_BUILD_ARM.ps1') -CubeIDEExe $CubeIDEExe
    } else {
        & (Join-Path $Root 'G1_BUILD_ARM.ps1')
    }
    if (-not $?) { throw 'G1_BUILD_ARM.ps1 returned unsuccessful status.' }
    $Manifest = Join-Path $Destination 'g1_arm_build.json'
    if (-not (Test-Path -LiteralPath $Manifest)) {throw 'The ARM build did not produce an authenticated pass manifest.'}
    $Details = Get-Content $Manifest -Raw | ConvertFrom-Json
    if ($Details.status -ne 'ARM_CLEAN_BUILD_PASS' -or -not (Test-Path -LiteralPath $Details.executable_path)) {
        throw 'The ARM binary is missing or the pass manifest is invalid.'
    }
    $ExitCode = 0
} catch {
    Write-Host "ARM BUILD FAILED: $($_.Exception.Message)" -ForegroundColor Red
    $ExitCode = 1
} finally {
    try { Stop-Transcript | Out-Null } catch { }
    foreach ($file in @('g1_arm_build.log','g1_arm_build_stderr.log','g1_arm_build.json','g1_preflight.json')) {
        $candidate = Join-Path $Destination $file
        if (Test-Path -LiteralPath $candidate) { Copy-Item -LiteralPath $candidate -Destination $Session -Force }
    }
    $meta = [ordered]@{
        project='G1_Product_R20_Battery_Standalone_CubeIDE119'; utc=(Get-Date).ToUniversalTime().ToString('o');
        exit_code=$ExitCode; verified_arm_build=($ExitCode -eq 0);
        diagnostics='Send this ZIP in the next message; no flashing was performed.'
    }
    $meta | ConvertTo-Json -Depth 3 | Out-File (Join-Path $Session 'result.json') -Encoding utf8
    $Notes = @'
This ZIP is generated by the actual CubeIDE headless build on your Windows machine.
Upload it to ChatGPT if the build fails. It includes the complete build stderr/stdout
and project identity. It is not proof of audio function or safety.
'@
    Set-Content (Join-Path $Session 'README.txt') $Notes
    $ZipPath = Join-Path $Destination "SEND_BUILD_TO_CHATGPT_$Stamp.zip"
    Compress-Archive -Path (Join-Path $Session '*') -DestinationPath $ZipPath -Force
    Write-Host "Diagnostic archive: $ZipPath" -ForegroundColor Cyan
    if ($ExitCode -eq 0) { Write-Host 'ARM compiler/linker build PASS' -ForegroundColor Green }
    else { Write-Host 'ARM build failed. Upload this diagnostics ZIP for the exact first error.' -ForegroundColor Red }
}
exit $ExitCode
