/* G1 native KiCad PCB explorer. SVG plots are exported from the unchanged board.
 * No invented PCB images, embedded schematic code, or renderer-controlled assets. */
"use strict";
const root=document.getElementById("pcbExplorer");
if(root){
  const frame=document.getElementById("pcbFrame");
  const image=document.getElementById("pcbPreview");
  const feedback=document.getElementById("pcbFeedback");
  const launch=document.getElementById("pcbOpenPlot");
  const views={front:"Front assembly",back:"Back assembly","front-copper":"Front copper","back-copper":"Back copper"};
  let available=new Map(),active="front",scale=1,tx=0,ty=0,drag=null;
  const clamp=(n,min,max)=>Math.min(max,Math.max(min,n));
  function transform(){image.style.transform="translate("+tx+"px,"+ty+"px) scale("+scale+")";}
  function reset(){scale=1;tx=0;ty=0;transform();}
  function show(id){
    if(!views[id])return;
    active=id;reset();
    const record=available.get(id);
    for(const button of root.querySelectorAll("[data-pcb-layer]")){
      button.setAttribute("aria-pressed",String(button.dataset.pcbLayer===id));
    }
    if(!record){image.removeAttribute("src");feedback.textContent="A native KiCad SVG view is generated by the Pages publishing workflow. Open the original PCB source while viewing the repository.";launch.hidden=true;return;}
    feedback.textContent=views[id]+" · native KiCad SVG · read-only design visualization";
    image.alt="Original G1 PCB: "+views[id]+" ("+record.layers+")";
    image.src="./"+record.path;
    launch.href="./"+record.path;launch.hidden=false;
  }
  root.querySelectorAll("[data-pcb-layer]").forEach(button=>button.addEventListener("click",()=>show(button.dataset.pcbLayer)));
  root.querySelector("[data-pcb-action='in']")?.addEventListener("click",()=>{scale=clamp(scale*1.2,1,8);transform();});
  root.querySelector("[data-pcb-action='out']")?.addEventListener("click",()=>{scale=clamp(scale/1.2,1,8);transform();});
  root.querySelector("[data-pcb-action='reset']")?.addEventListener("click",reset);
  frame.addEventListener("wheel",e=>{
    if(!image.hasAttribute("src"))return;
    e.preventDefault();scale=clamp(scale*(e.deltaY>0?.9:1.1),1,8);transform();
  },{passive:false});
  frame.addEventListener("pointerdown",e=>{
    if(e.button!==0||!image.hasAttribute("src"))return;
    drag={id:e.pointerId,x:e.clientX,y:e.clientY,tx,ty};
    frame.setPointerCapture(e.pointerId);
  });
  frame.addEventListener("pointermove",e=>{
    if(!drag||drag.id!==e.pointerId)return;
    tx=drag.tx+e.clientX-drag.x;ty=drag.ty+e.clientY-drag.y;transform();
  });
  for(const eventName of ["pointerup","pointercancel","lostpointercapture"]){
    frame.addEventListener(eventName,()=>{drag=null;});
  }
  image.addEventListener("error",()=>{feedback.textContent="KiCad SVG preview unavailable. Open the source PCB in KiCad.";launch.hidden=true;});
  fetch("./plots/pcb/manifest.json",{cache:"no-store"}).then(r=>r.ok?r.json():null).then(data=>{
    if(data?.view_only===true&&Array.isArray(data.views)){
      available=new Map(data.views.filter(v=>views[v.id]&&v.path.startsWith("plots/pcb/")&&!v.path.includes("..")).map(v=>[v.id,v]));
    }
    show(active);
  }).catch(()=>show(active));
}
